#!/usr/bin/env python3
"""Gzip web/index.html into web_ui.h (PROGMEM) so the sketch needs no LittleFS upload step.
Usage: python make_web_ui.py web/index.html web_ui.h"""
import gzip, sys
data = gzip.compress(open(sys.argv[1], "rb").read(), 9, mtime=0)
with open(sys.argv[2], "w") as f:
    f.write("// Generated by tools/make_web_ui.py - do not edit.\n#pragma once\n#include <Arduino.h>\n#include <pgmspace.h>\n")
    f.write("const size_t WEB_UI_LEN = %d;\nconst uint8_t WEB_UI[] PROGMEM = {\n" % len(data))
    for i in range(0, len(data), 24):
        f.write("  " + ",".join("0x%02x" % b for b in data[i:i+24]) + ",\n")
    f.write("};\n")
print("gzip bytes:", len(data))
